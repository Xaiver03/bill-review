def kw_lookup(text):
    t = text or ''
    for sub, l1, l2 in KW:
        if sub in t:
            return l1, l2
    return None


def src_account(src, pm):
    pm = pm or ''
    if src == 'wechat':
        if '工商银行' in pm: return '工商银行'
        if '招商' in pm: return '招商银行'
        if '零钱通' in pm: return '微信零钱通'
        return '微信零钱'
    if src == 'alipay':
        if '花呗' in pm: return '支付宝花呗'
        if '余额宝' in pm: return '支付宝余额宝'
        return '支付宝'
    if src == 'icbc': return '工商银行'
    if src == 'cmb': return '招商银行'
    return src or '其他'


def _amt(v):
    try:
        return abs(float(v or 0))
    except Exception:
        return 0.0


def classify_rows(rows, knowledge=None):
    """四级规则分类 + 知识库叠加。

    knowledge: {merchant: {"l1":..., "l2":..., "count":...}}，用户复核沉淀的商户先验。
    命中顺序：type > PRECISE > 退款 > 转账/neutral > 投资 > 关键词规则 > 知识库 > 同商户先验 > 待分类。
    知识库与同商户先验都在 else 分支触发，关键词规则优先于知识库。
    """
    knowledge = knowledge or {}
    prior = defaultdict(Counter)
    for r in rows:
        c = (r.get('category') or '').strip()
        if c in PRECISE:
            prior[(r.get('counterparty') or '').strip()][PRECISE[c][0]] += 1
    prior_best = {}
    for cp, cnt in prior.items():
        l1, n = cnt.most_common(1)[0]
        if sum(cnt.values()) >= 2 and n / sum(cnt.values()) >= 0.6:
            prior_best[cp] = l1
    out = []
    for r in rows:
        cat = (r.get('category') or '').strip(); cp = (r.get('counterparty') or '').strip()
        note = (r.get('note') or '').strip(); t = (r.get('type') or '').strip()
        amt = _amt(r.get('amount'))
        L1 = L2 = None; conf = 0.0; by = ''
        if t == 'income':
            L1 = '收入'
            L2 = '工资' if '工资' in cat else ('经营' if '经营' in cat else ('红包' if '红包' in cat else '其他收入'))
            conf = 0.9 if cat in ('收入','经营收款','二维码收款','群收款','微信红包','微信红包（群红包）','微信红包（单发）') else 0.6
            by = 'type'
        elif cat in PRECISE:
            L1, L2 = PRECISE[cat]; conf = 0.95; by = 'cat'
        elif '退款' in cat:
            hit = kw_lookup(cat)
            if hit: L1, L2 = hit[0], '退款'; conf = 0.8; by = 'refund'
            else: L1, L2 = '退款/冲正', None; conf = 0.6; by = 'refund'
        elif cat in TRANSFER or t == 'neutral':
            L1 = '转账还款'; L2 = TRANSFER.get(cat, '账户互转'); conf = 0.85; by = 'transfer'
        elif cat in INVEST:
            L1 = '投资理财'; L2 = None; conf = 0.9; by = 'invest'
        else:
            hit = kw_lookup(cp + ' ' + note + ' ' + cat)
            if hit:
                L1, L2 = hit; conf = 0.7; by = 'rule'
            elif cp and cp in knowledge:
                kb = knowledge[cp] or {}
                L1 = kb.get('l1') or '其他'; L2 = kb.get('l2') or ''
                cnt = int(kb.get('count', 1) or 1)
                conf = 0.9 if cnt >= 2 else 0.8
                by = 'knowledge'
            elif cp in prior_best:
                L1, L2 = prior_best[cp], None; conf = 0.6; by = 'prior'
            else:
                L1, L2 = '其他', '待分类'; conf = 0.2; by = 'none'
        need = (by == 'none') or (conf < 0.6)
        rr = dict(r)
        rr.update(purpose_l1=L1, purpose_l2=L2 or '', confidence=round(conf, 2),
                  classify_by=by, needs_review='1' if need else '0', amount_abs=amt,
                  account=src_account(r.get('source'), r.get('payment_method')))
        out.append(rr)
    return out


def read_csv(path):
    with open(path, newline='', encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def _cols(rows, extra):
    base = []
    for r in rows:
        for k in r.keys():
            if k not in base: base.append(k)
    for e in extra:
        if e not in base: base.append(e)
    return base


CLS_EXTRA = ['purpose_l1','purpose_l2','confidence','classify_by','needs_review','account']


def write_classified(rows, outdir):
    import os
    path = os.path.join(outdir, 'classified.csv')
    cols = _cols(rows, CLS_EXTRA)
    with open(path, 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction='ignore'); w.writeheader()
        for r in rows: w.writerow(r)
    return path


def compute_stats(rows):
    rq = [r for r in rows if r.get('needs_review') == '1']
    return {
        'total': len(rows), 'review': len(rq), 'auto': len(rows) - len(rq),
        'review_pct': round(len(rq) * 100 / max(len(rows), 1), 1),
        'auto_pct': round((len(rows) - len(rq)) * 100 / max(len(rows), 1), 1),
        'by_method': dict(Counter(r.get('classify_by') for r in rows)),
        'by_purpose': dict(Counter(r.get('purpose_l1') for r in rows)),
    }
